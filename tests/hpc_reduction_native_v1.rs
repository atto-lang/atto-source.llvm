// Native AttoLang guest execution gate; Rust test harness, not a numeric stand-in.
// Build real compiler/IR auditor first, then run under a stepful exact-head job.
// Targets one source Task<int>; no multicore, SIMD or f64 claim.
use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::time::{SystemTime, UNIX_EPOCH};

fn require(ok: bool, reason: impl AsRef<str>) {
    if !ok {
        eprintln!("ATTO_HPC_V1_REJECTED: {}", reason.as_ref());
        std::process::exit(1);
    }
}
fn cmd(program: &str, args: &[&str]) -> Output {
    let result = Command::new(program).args(args).output();
    match result {
        Ok(o) => o,
        Err(e) => { eprintln!("ATTO_HPC_V1_REJECTED: spawn {program}: {e}"); std::process::exit(1); }
    }
}
fn text(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).trim().to_owned()
}
fn exec(program: &str, args: &[&str]) -> String {
    let output = cmd(program, args);
    require(output.status.success(), format!("{program}: {}", String::from_utf8_lossy(&output.stderr)));
    text(&output)
}
fn file_hash(path: &Path) -> String {
    let s = path.to_str().expect("UTF-8 paths required");
    let output = exec("sha256sum", &[s]);
    let hash = output.split_whitespace().next().unwrap_or("");
    require(hash.len() == 64 && hash.chars().all(|c| c.is_ascii_hexdigit()), "malformed SHA256");
    hash.to_owned()
}
fn trusted_file(path: &Path) {
    let info = fs::symlink_metadata(path).unwrap_or_else(|e| {
        eprintln!("ATTO_HPC_V1_REJECTED: {}: {e}", path.display());
        std::process::exit(1);
    });
    require(info.is_file() && !info.file_type().is_symlink(), format!("not a regular file: {}", path.display()));
}
fn source_matches_head(path: &str) {
    trusted_file(Path::new(path));
    let head_blob = exec("git", &["rev-parse", &format!("HEAD:{path}")]);
    let working_blob = exec("git", &["hash-object", "--no-filters", "--", path]);
    require(head_blob == working_blob, format!("unreviewed source bytes: {path}"));
}
struct TempDir(PathBuf);
impl TempDir {
    fn new() -> Self {
        let tick = SystemTime::now().duration_since(UNIX_EPOCH).expect("clock").as_nanos();
        let path = env::temp_dir().join(format!("atto-hpc-v1-{}-{tick}", std::process::id()));
        fs::create_dir(&path).expect("private work directory");
        #[cfg(unix)] {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(&path, fs::Permissions::from_mode(0o700)).expect("private directory permissions");
        }
        Self(path)
    }
}
impl Drop for TempDir {
    fn drop(&mut self) { let _ = fs::remove_dir_all(&self.0); }
}
fn main() {
    const SOURCES: [&str; 2] = [
        "tests/fixtures/hpc-reduction-v1/i64-fixed-tiles.atto",
        "tests/fixtures/hpc-reduction-v1/i64-task-tile.atto",
    ];
    const NEGATIVES: [(&str, &str); 4] = [
        ("tests/fixtures/task-v1-negative/second-task.atto",
         "supports exactly one source Task"),
        ("tests/fixtures/task-v1-negative/producer-call.atto",
         "producer must be capture-free and scalar"),
        ("tests/fixtures/hpc-reduction-v1/mutable-before-await-reject.atto",
         "requires await to immediately consume"),
        ("tests/fixtures/hpc-reduction-v1/two-caller-tiles-reject.atto",
         "requires await to immediately consume"),
    ];
    let head = env::var("EXPECTED_HEAD").unwrap_or_default();
    require(head.len() == 40 && head.chars().all(|c| c.is_ascii_hexdigit()), "EXPECTED_HEAD must be exact SHA40");
    require(exec("git", &["rev-parse", "HEAD"]) == head, "worktree HEAD differs from expected immutable commit");
    require(exec("git", &["status", "--porcelain", "--", "tests/fixtures/hpc-reduction-v1"]).is_empty(),
            "HPC fixtures have uncommitted changes");
    for source in SOURCES { source_matches_head(source); }
    for (negative, _) in NEGATIVES { source_matches_head(negative); }
    let compiler = Path::new("build/oreslang-llvmc");
    let auditor = Path::new("build/oreslang-no-gc-ir-audit");
    trusted_file(compiler);
    trusted_file(auditor);
    let compiler_hash = file_hash(compiler);
    let work = TempDir::new();
    let mut executed = 0u32;
    for (i, source) in SOURCES.iter().enumerate() {
        let src_hash = file_hash(Path::new(source));
        // Require the native Atto frontend to produce actual LLVM IR. The
        // Clang driver below must consume source-compiler IR, never a host
        // surrogate generated by this test runner.
        let emitted = cmd("timeout",
            &["-k", "5s", "45s", "build/oreslang-llvmc", "--target=host", source]);
        require(emitted.status.success(),
            format!("native frontend rejected {source}: {}",
                String::from_utf8_lossy(&emitted.stderr)));
        let ir = String::from_utf8_lossy(&emitted.stdout);
        require(ir.contains("define i64 @__oreslang_guest_main("),
            format!("{source}: missing compiler-produced guest entrypoint"));
        if i == 1 {
            for abi in [
                "oreslang_source_task_start_i64",
                "oreslang_source_task_await_i64",
                "oreslang_source_task_runtime_shutdown",
            ] {
                require(ir.contains(abi),
                    format!("{source}: missing actual native Task ABI {abi}"));
            }
        }
        for level in ["0", "2"] {
            let binary = work.0.join(format!("tile-{i}-o{level}"));
            let binary_str = binary.to_str().expect("work path utf8");
            let output = Command::new("timeout")
                .args(["-k", "5s", "90s", "bash", "scripts/compile-aot.sh", source, binary_str])
                .env("ORESLANG_LLVM_AOT_OPT_LEVEL", level).output().expect("run AOT compiler");
            require(output.status.success(), format!("LLVM AOT failed {source} O{level}: {}", String::from_utf8_lossy(&output.stderr)));
            trusted_file(&binary);
            let guest = cmd("timeout", &["-k", "3s", "15s", binary_str]);
            require(guest.status.code() == Some(42),
                    format!("guest {source} O{level}: status={:?}; stderr={}", guest.status,
                            String::from_utf8_lossy(&guest.stderr)));
            require(guest.stdout.is_empty() && guest.stderr.is_empty(), format!("guest {source} printed unexpected output"));
            require(file_hash(Path::new(source)) == src_hash, "source modified during execution");
            require(file_hash(compiler) == compiler_hash, "compiler modified during execution");
            let artifact = file_hash(&binary);
            println!("ATTO_HPC_I64_GUEST_PASS head={head} source={source} opt=O{level} exit=42 compiler_sha256={compiler_hash} source_sha256={src_hash} binary_sha256={artifact}");
            executed += 1;
        }
    }
    // Reject both two live Tasks and a mutable caller tile before await.
    // Neither invalid source may publish native IR or an executable.
    for (index, (negative, required_diagnostic)) in NEGATIVES.iter().enumerate() {
        let invalid_output = work.0.join(format!("rejected-{index}"));
        let invalid_str = invalid_output.to_str().expect("work path utf8");
        let compiler_rejection = cmd("timeout",
            &["-k", "5s", "45s", "build/oreslang-llvmc", "--target=host",
              negative]);
        require(!compiler_rejection.status.success() &&
                compiler_rejection.status.code() != Some(124) &&
                compiler_rejection.status.code() != Some(137),
                format!("invalid source unexpectedly admitted by compiler: {negative}"));
        require(compiler_rejection.stdout.is_empty(),
                format!("compiler emitted LLVM IR for rejected source: {negative}"));
        require(String::from_utf8_lossy(&compiler_rejection.stderr)
                .contains(required_diagnostic),
                format!("wrong direct compiler diagnostic for {negative}: {}",
                    String::from_utf8_lossy(&compiler_rejection.stderr)));
        let rejected = cmd("timeout",
            &["-k", "5s", "60s", "bash", "scripts/compile-aot.sh",
              negative, invalid_str]);
        require(!rejected.status.success() && rejected.status.code() != Some(124) && rejected.status.code() != Some(137),
                format!("invalid source compiled or timed out: {negative}"));
        require(!invalid_output.exists(),
                format!("rejected source published executable: {negative}"));
        let diagnostic = String::from_utf8_lossy(&rejected.stderr);
        require(diagnostic.contains(required_diagnostic),
                format!("unexpected diagnostic for {negative}: {diagnostic}"));
    }
    require(exec("git", &["status", "--porcelain", "--", "tests/fixtures/hpc-reduction-v1"]).is_empty(),
            "HPC source changed during verification");
    require(executed == 4, "missing O0/O2 compiled guest executions");
    println!("ATTO_HPC_I64_GATE_PASS head={head} executed_guest_cases={executed} negative_cases=4 evidence_scope=restricted_i64_native_aot");
}
