"""Strict verifier for *executed* LLVM M1 guest receipt; does not execute guests.

A receipt is meaningful only when generated by an authorized exact-head
workflow after real compiler-backed guest execution. This tool validates
content, NOT authenticity or compiler provenance.
"""
import argparse
import json
from pathlib import Path
import re

SHA40 = re.compile(r"[0-9a-f]{40}\Z")
SHA256 = re.compile(r"[0-9a-f]{64}\Z")
CASES = frozenset((e, o) for e in ("atto", "ores") for o in ("-O0", "-O2"))
TOP_KEYS = frozenset((
    "schema", "evidenceClassification", "headSha", "treeSha",
    "compilerSha256", "cases", "defaultRetention", "negativeAdmissions", "scope"
))
CASE_KEYS = frozenset((
    "sourceExtension", "optimization", "exitCode", "nativeSha256",
    "descriptorSha256", "compilerMetadataSha256", "descriptorBytes"
))


def _valid_sha(value, pattern):
    return type(value) is str and pattern.fullmatch(value) is not None


def validate(receipt, expected_head, expected_tree):
    """Raises ValueError on any unverified or contradictory evidence claim."""
    if not _valid_sha(expected_head, SHA40) or not _valid_sha(expected_tree, SHA40):
        raise ValueError("trusted source head/tree must be 40 lowercase hex characters")
    if type(receipt) is not dict or receipt.keys() != TOP_KEYS:
        raise ValueError("invalid receipt top-level fields")
    fixed = {
        "schema": "atto.mcp.llvm-aot-guest-evidence.v1",
        "evidenceClassification": "COMPILER_BACKED_NATIVE_GUEST_EXECUTED",
        "defaultRetention": "ABSENT_AT_O0_AND_O2",
        "negativeAdmissions": "PASS",
        "scope": "M1_ELF_GUEST_DESCRIPTOR_ONLY_NOT_MCP_SERVER",
    }
    for key, expected in fixed.items():
        if receipt[key] != expected or type(receipt[key]) is not str:
            raise ValueError("unsupported receipt schema, scope, or assertion")
    if receipt["headSha"] != expected_head or receipt["treeSha"] != expected_tree:
        raise ValueError("receipt source identity differs from checked-out head/tree")
    if not _valid_sha(receipt["compilerSha256"], SHA256):
        raise ValueError("invalid compiler binary digest")
    cases = receipt["cases"]
    if type(cases) is not list or len(cases) != 4:
        raise ValueError("exactly four native guest executions are required")
    observed = set()
    descriptor_digests = set()
    compiler_metadata_digests = set()
    descriptor_sizes = set()
    for case in cases:
        if type(case) is not dict or case.keys() != CASE_KEYS:
            raise ValueError("invalid native guest case fields")
        identity = (case["sourceExtension"], case["optimization"])
        if not all(type(value) is str for value in identity):
            raise ValueError("invalid native guest case identifier types")
        if identity not in CASES or identity in observed:
            raise ValueError("unknown or duplicate native guest case")
        observed.add(identity)
        if type(case["exitCode"]) is not int or case["exitCode"] != 42:
            raise ValueError("native guest did not return the expected result")
        if type(case["descriptorBytes"]) is not int or not 2 <= case["descriptorBytes"] <= 8193:
            raise ValueError("native guest descriptor byte budget invalid")
        for name in ("nativeSha256", "descriptorSha256", "compilerMetadataSha256"):
            if not _valid_sha(case[name], SHA256):
                raise ValueError("invalid native binary or descriptor digest")
        descriptor_digests.add(case["descriptorSha256"])
        compiler_metadata_digests.add(case["compilerMetadataSha256"])
        descriptor_sizes.add(case["descriptorBytes"])
    if observed != CASES:
        raise ValueError("native guest case coverage incomplete")
    if len(descriptor_digests) != 1 or len(compiler_metadata_digests) != 1 or len(descriptor_sizes) != 1:
        raise ValueError("LLVM O0/O2 or .atto/.ores descriptor parity failed")
    return True


def _unique_pairs(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError("duplicate receipt JSON key")
        result[key] = value
    return result


def load_receipt(path):
    blob = Path(path).read_bytes()
    if not blob or len(blob) > 32768:
        raise ValueError("native receipt missing or over 32 KiB")
    return json.loads(blob.decode("utf-8"), object_pairs_hook=_unique_pairs,
                      parse_constant=lambda _: (_ for _ in ()).throw(ValueError("non-finite receipt JSON number")))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--receipt", type=Path, required=True)
    parser.add_argument("--expected-head", required=True)
    parser.add_argument("--expected-tree", required=True)
    args = parser.parse_args()
    if not __debug__:
        raise SystemExit("INVALID_TEST_ENVIRONMENT: Python -O disables assertions")
    try:
        validate(load_receipt(args.receipt), args.expected_head, args.expected_tree)
    except (OSError, UnicodeError, ValueError, TypeError) as exc:
        raise SystemExit(f"INVALID_COMPILER_GUEST_RECEIPT: {exc}") from None
    print("VERIFIED_FORMAT_ONLY: exact-head four-case LLVM M1 guest receipt (requires trusted workflow provenance)")


if __name__ == "__main__":
    main()
